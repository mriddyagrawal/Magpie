"""Fetch + register the `receipts` eval corpus from SROIE (PLAN.md §6).

Source: HF dataset jsdnrs/ICDAR2019-SROIE (CC-BY-4.0 mirror of ICDAR-2019
SROIE), test split, revision-pinned. Deterministic: same inputs, same corpus,
byte-for-byte.

  corpus   150 receipt JPEGs (sorted order, first 150 of the test split)
           -> OUTSIDE the repo (default ~/Documents/Magpie-eval-corpora/receipts),
           subfoldered batch_NN/ (<=14 images each)
  manifest eval_harness/datasets/receipts/manifest.json (committed; sha256s +
           subfolder-relative paths)
  pointer  eval_harness/datasets/receipts/corpus_root.local.json (untracked,
           per-machine)

This script prepares the CORPUS only. It does not write golden.json or
qrels.tsv: questions are generated by agents that read the actual files
(the /magpie-eval skill, Phase 2) - the label-derived question generator
that used to live here was retired 2026-08-30 (owner decision 2026-08-29:
questions must come from reading files, and a script that could overwrite
the agent-written golden was a footgun).

Run (one-time prep; eval runs themselves stay offline):
  uv run --with datasets --with pillow python eval_harness/scripts/prepare_receipts.py
  uv run python eval_harness/scripts/prepare_receipts.py --verify
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
DATASET_DIR = REPO / "eval_harness" / "datasets" / "receipts"
DEFAULT_CORPUS = Path.home() / "Documents" / "Magpie-eval-corpora" / "receipts"

N_CORPUS = 150          # decided 2026-08-28 (PLAN §9.5)
# Pinned dataset revision (review #41): resolved 2026-08-28. Without a pin,
# "deterministic" depends on whatever HEAD resolves on rerun day.
REVISION = "bffe40c26759f3376ec2b3ae9031dbba54cd587c"

# <=14 images per subfolder. Historical note: this disarmed the walker's
# since-removed asset-library heuristic; it stays because small folders also
# keep any future per-folder logic and file browsing sane.
BATCH_SIZE = 14


def sha256_file(p: Path) -> str:
    h = hashlib.sha256()
    with p.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def load_split():
    from datasets import Image, load_dataset

    ds = load_dataset("jsdnrs/ICDAR2019-SROIE", split="test", revision=REVISION)
    # decode=False -> original bytes written verbatim (review #40): no second
    # lossy JPEG pass altering the pixels a visual retriever reads.
    ds_raw = ds.cast_column("image", Image(decode=False))
    rows = []
    for i, row in enumerate(ds_raw):
        rows.append({"i": i, **{k: row[k] for k in row.keys()}})
    return rows


def _resolve(corpus_dir: Path, entry: dict) -> Path | None:
    """Find a manifest entry on disk: exact relative `path` first, then a
    recursive basename search (#126: the manifest used to store flat names
    while the corpus is subfoldered - verify reported 148/148 MISSING on a
    perfectly good corpus)."""
    if entry.get("path"):
        p = corpus_dir / entry["path"]
        if p.exists():
            return p
    hits = list(corpus_dir.rglob(entry["name"]))
    return hits[0] if hits else None


def verify(corpus_dir: Path) -> int:
    """Re-hash the on-disk corpus against the committed manifest (review #41:
    the sha256s exist to be load-bearing, not decorative)."""
    manifest = json.loads((DATASET_DIR / "manifest.json").read_text(encoding="utf-8"))
    bad = 0
    for entry in manifest["files"]:
        p = _resolve(corpus_dir, entry)
        if p is None:
            print(f"MISSING {entry['name']}")
            bad += 1
        elif sha256_file(p) != entry["sha256"]:
            print(f"HASH MISMATCH {entry['name']}")
            bad += 1
    print(f"verify: {len(manifest['files']) - bad}/{len(manifest['files'])} files OK")
    return 1 if bad else 0


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--corpus-dir", default=str(DEFAULT_CORPUS))
    ap.add_argument("--verify", action="store_true",
                    help="re-hash the corpus against the committed manifest and exit")
    args = ap.parse_args()
    corpus_dir = Path(args.corpus_dir).expanduser()

    if args.verify:
        raise SystemExit(verify(corpus_dir))

    rows = load_split()
    rows = rows[:N_CORPUS]
    corpus_dir.mkdir(parents=True, exist_ok=True)

    files: list[dict] = []
    for idx, r in enumerate(sorted(rows, key=lambda r: r["i"])):
        name = f"receipt_{Path(r['image']['path']).stem}.jpg" if r["image"].get("path") \
            else f"receipt_{r['i']:04d}.jpg"
        sub = f"batch_{idx // BATCH_SIZE:02d}"
        (corpus_dir / sub).mkdir(exist_ok=True)
        dest = corpus_dir / sub / name
        dest.write_bytes(r["image"]["bytes"])
        files.append({"name": name, "path": f"{sub}/{name}",
                      "sha256": sha256_file(dest)})

    files.sort(key=lambda f: f["name"])
    (DATASET_DIR / "manifest.json").write_text(json.dumps({
        "dataset": "receipts",
        "source": "jsdnrs/ICDAR2019-SROIE (test split; CC-BY-4.0)",
        "source_revision": REVISION,
        "n_files": len(files),
        "selection": f"first {N_CORPUS} of test split under deterministic sort",
        "layout": f"batch_NN/ subfolders, <= {BATCH_SIZE} images each",
        "files": files,
    }, indent=2) + "\n", encoding="utf-8")

    (DATASET_DIR / "corpus_root.local.json").write_text(
        json.dumps({"corpus_root": str(corpus_dir)}, indent=2) + "\n", encoding="utf-8")

    print(f"corpus: {len(files)} images -> {corpus_dir} (subfoldered)")
    print(f"manifest + local pointer written under {DATASET_DIR}")
    print("golden.json/qrels.tsv are NOT written here - the /magpie-eval "
          "skill generates them by reading the files.")


if __name__ == "__main__":
    main()
